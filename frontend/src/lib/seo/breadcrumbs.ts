// BreadcrumbList JSON-LD builder. Each marketing page calls this
// with its own crumb chain. Mirrors the existing pattern in
// src/app/(shop)/blog/[slug]/page.tsx.

export interface BreadcrumbItem {
  name: string;
  url: string;
}

export function buildBreadcrumbJsonLd(items: BreadcrumbItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: item.url,
    })),
  };
}
