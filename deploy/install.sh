# with_timeout SECONDS CMD...: run CMD, killing it after SECONDS (a wedged
# daemon makes every docker call hang). Uses timeout(1) when present, else a
# watchdog, so it also works on a stock macOS.
with_timeout() {
	local secs=$1 pid watcher status=0
	shift
	if have timeout; then
		timeout "$secs" "$@"
		return
	fi
	"$@" &
	pid=$!
	(
		sleep "$secs"
		kill -TERM "$pid" 2>/dev/null
	) >/dev/null 2>&1 </dev/null &
	watcher=$!
	wait "$pid" || status=$?
	kill "$watcher" 2>/dev/null || true
	wait "$watcher" 2>/dev/null || true
	return "$status"
}

# docker_answers: the daemon replies within DOCKER_TIMEOUT seconds.
docker_answers() {
	with_timeout "$DOCKER_TIMEOUT" docker info >/dev/null 2>&1
}

docker_up=0
check_docker() {
	step "Checking Docker"
	if ! have docker; then
		[[ $dry_run == 1 ]] && {
			warn "docker not found (install Docker Engine: https://docs.docker.com/engine/install/)"
			return 0
		}
		die "docker not found. Install Docker Engine and the Compose plugin: https://docs.docker.com/engine/install/"
	fi
	local cv
	if ! cv=$(with_timeout "$DOCKER_TIMEOUT" docker compose version --short 2>/dev/null); then
		[[ $dry_run == 1 ]] && {
			warn "the Docker Compose v2 plugin is missing"
			return 0
		}
		die "the Docker Compose v2 plugin is missing ('docker compose', not 'docker-compose'). Install docker-compose-plugin: https://docs.docker.com/compose/install/linux/"
	fi
	cv=${cv#v}
	if ! version_ge "$cv" "$MIN_COMPOSE"; then
		die "Docker Compose $cv is too old; $MIN_COMPOSE or newer is required"
	fi
	if ! docker_answers; then
		local hint="start (or restart) the Docker daemon"
		if [[ $(id -u) -ne 0 ]]; then
			hint="start the Docker daemon, or run as root / add $(id -un) to the docker group"
		fi
		[[ $dry_run == 1 ]] && {
			warn "cannot talk to the Docker daemon: $hint"
			return 0
		}
		die "cannot talk to the Docker daemon: $hint"
	fi
	docker_up=1
	note "Docker $(with_timeout "$DOCKER_TIMEOUT" docker version --format '{{.Server.Version}}' 2>/dev/null || echo '?'), Compose $cv"
}

# Name of the compose project in install_dir (the `name:` key unless
# COMPOSE_PROJECT_NAME overrides it).
project_name() {
	local name=${COMPOSE_PROJECT_NAME:-}
	if [[ -z $name && -f $install_dir/.env ]]; then
		name=$(env_get COMPOSE_PROJECT_NAME "$install_dir/.env")
	fi
	if [[ -z $name && -f $install_dir/docker-compose.yml ]]; then
		name=$(sed -n 's/^name:[[:space:]]*\([A-Za-z0-9_-]*\).*/\1/p' "$install_dir/docker-compose.yml" | head -n 1)
	fi
	printf '%s' "${name:-payverge}"
}

