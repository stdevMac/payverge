sha256_check() { # sha256_check SUMFILE (in the current directory)
	if have sha256sum; then
		sha256sum -c --status "$1"
	elif have shasum; then
		shasum -a 256 -c -s "$1"
	else
		die "need sha256sum or shasum to verify the download"
	fi
}

# verify_release_signature BASE: trust SHA256SUMS in the current directory
# only after its keyless cosign bundle checks out. Dry-run prints the
# download and the cosign command. Cosign missing is a note here; the hard
# stop for --require-signature happens before any download.
verify_release_signature() {
	local base=$1
	if ! have cosign; then
		note "only the checksum is checked; install cosign (https://docs.sigstore.dev/cosign/system_config/installation/) and re-run with --require-signature to verify the signature of SHA256SUMS"
		return 0
	fi
	if [[ $dry_run == 1 ]]; then
		run curl -fsSLO "$base/SHA256SUMS.sigstore.json"
		run cosign verify-blob --bundle SHA256SUMS.sigstore.json \
			--certificate-identity "$RELEASE_SIGNER" \
			--certificate-oidc-issuer https://token.actions.githubusercontent.com \
			SHA256SUMS
		return 0
	fi
	curl -fsSL --proto '=https' --tlsv1.2 -o SHA256SUMS.sigstore.json "$base/SHA256SUMS.sigstore.json" ||
		die "download failed: $base/SHA256SUMS.sigstore.json"
	cosign verify-blob --bundle SHA256SUMS.sigstore.json \
		--certificate-identity "$RELEASE_SIGNER" \
		--certificate-oidc-issuer https://token.actions.githubusercontent.com \
		SHA256SUMS ||
		die "signature check failed for SHA256SUMS; not installing it"
	note "signature verified (cosign)"
}

fetch_release() { # fetch_release VERSION
	local v=$1 tmp tarball="payverge-deploy-$1.tar.gz" base="$RELEASES_URL/download/v$1"
	if [[ $require_signature == 1 ]] && ! have cosign; then
		die "cosign is required to verify the release signature; install it (https://docs.sigstore.dev/cosign/system_config/installation/) or drop --require-signature"
	fi
	step "Downloading release v$v"
	if [[ $dry_run == 1 ]]; then
		run curl -fsSLO "$base/$tarball"
		run curl -fsSLO "$base/SHA256SUMS"
		verify_release_signature "$base"
		run sha256sum -c "(the $tarball line of SHA256SUMS)"
		run tar -xzf "$tarball" --strip-components=1 -C "$install_dir"
		return 0
	fi
	tmp=$(mktemp -d)
	# shellcheck disable=SC2064 # expand tmp now
	trap "rm -rf '$tmp'" EXIT
	(
		cd "$tmp"
		curl -fsSL --proto '=https' --tlsv1.2 -o "$tarball" "$base/$tarball" ||
			die "download failed: $base/$tarball"
		curl -fsSL --proto '=https' --tlsv1.2 -o SHA256SUMS "$base/SHA256SUMS" ||
			die "download failed: $base/SHA256SUMS"
		verify_release_signature "$base"
		awk -v f="$tarball" '$2 == f || $2 == "*" f' SHA256SUMS >one.sum
		[[ -s one.sum ]] || die "SHA256SUMS has no entry for $tarball"
		sha256_check one.sum || die "checksum mismatch for $tarball; not installing it"
		mkdir stage
		tar -xzf "$tarball" --strip-components=1 -C stage
	)
	note "checksum verified"
	mkdir -p "$install_dir"
	install_tree "$tmp/stage" "$install_dir"
	rm -rf "$tmp"
	trap - EXIT
}

# install_tree SRC DEST: copy every file of SRC into DEST. Each file is
# renamed into place, so the install.sh running right now keeps reading its
# old copy. .env, backups/ and rclone/ are not in a release and stay as they are.
install_tree() {
	local src=$1 dest=$2 f
	while IFS= read -r f; do
		f=${f#./}
		mkdir -p "$dest/$(dirname "$f")"
		cp -p "$src/$f" "$dest/$f.new.$$"
		mv -f "$dest/$f.new.$$" "$dest/$f"
	done < <(cd "$src" && find . -type f)
}

copy_checkout() {
	local f
	step "Copying the deploy files from $local_source"
	run mkdir -p "$install_dir/backup" "$install_dir/postgres" "$install_dir/monitoring"
	for f in $DEPLOY_FILES; do
		[[ -f $local_source/$f ]] || continue
		run cp -p "$local_source/$f" "$install_dir/$f"
	done
	note "docker-compose.build.yml builds from ../backend and ../frontend; use it from the checkout itself."
}

