interactive() {
	[[ $assume_yes != 1 ]] && [[ -r /dev/tty ]] && { : </dev/tty; } 2>/dev/null
}

# ask VAR PROMPT [DEFAULT]: read one line from the terminal (works under
# curl | bash, where stdin is the script).
ask() {
	local __var=$1 __prompt=$2 __default=${3:-} __reply=""
	if [[ -n $__default ]]; then
		__prompt="$__prompt [$__default]"
	fi
	printf '%s: ' "$__prompt" >/dev/tty
	IFS= read -r __reply </dev/tty || true
	[[ -n $__reply ]] || __reply=$__default
	printf -v "$__var" '%s' "$__reply"
}

valid_domain() {
	local d=$1
	[[ ${#d} -le 253 ]] || return 1
	[[ $d =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] && return 0
	[[ $d =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$ ]]
}

# normalize_domain: lower-case DOMAIN and strip a scheme or path pasted with it.
normalize_domain() {
	domain=$(lower "$domain")
	domain=${domain#http://}
	domain=${domain#https://}
	domain=${domain%%/*}
	valid_domain "$domain" || die "'$domain' is not a valid host name"
}

valid_email() {
	[[ $1 =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ || $1 =~ ^[^[:space:]@]+@localhost$ ]]
}

valid_port() {
	[[ $1 =~ ^[0-9]+$ ]] && ((10#$1 >= 1 && 10#$1 <= 65535))
}

# valid_port_spec VALUE: PORT, IPV4:PORT or [IPV6]:PORT (what compose accepts
# on the host side of a port mapping).
valid_port_spec() {
	local v=$1
	if [[ $v == *:* ]]; then
		local addr=${v%:*}
		[[ $addr =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ || $addr =~ ^\[[0-9A-Fa-f:.]+\]$ ]] || return 1
		v=${v##*:}
	fi
	valid_port "$v"
}

# loopback_name NAME: a trial name that only this machine can reach, so the
# stack is published on 127.0.0.1 instead of every interface.
loopback_name() {
	case $1 in
	localhost | *.localhost | 127.*) return 0 ;;
	*) return 1 ;;
	esac
}

# bind_loopback: localhost trial ports default to 127.0.0.1 (an explicit
# ADDR:PORT, such as 0.0.0.0:8443, is kept).
bind_loopback() {
	[[ $http_port == *:* ]] || http_port=127.0.0.1:${http_port:-80}
	[[ $https_port == *:* ]] || https_port=127.0.0.1:${https_port:-443}
}

# valid_project_name NAME: what docker compose accepts for a project name.
valid_project_name() {
	[[ $1 =~ ^[a-z0-9][a-z0-9_-]*$ ]]
}

# Served with a certificate from Caddy's own CA instead of a public one.
# valid_proxy_cidrs VALUE: TRUSTED_PROXY_CIDRS is a space-separated list of
# IPv4/IPv6 addresses or CIDRs (or Caddy's private_ranges). Caddy splices it
# into its global options, so anything else would break or widen the config.
# Ranges broader than /8 (IPv4) or /16 (IPv6) are refused: a /0, or a pair of
# /1 halves, would trust every client's X-Forwarded-For.
valid_proxy_cidrs() {
	local token ip prefix
	set -f
	# shellcheck disable=SC2086 # word splitting on spaces is the format
	set -- $1
	set +f
	(($# > 0)) || return 1
	for token in "$@"; do
		[[ $token != private_ranges ]] || continue
		ip=${token%%/*}
		prefix=
		[[ $token != */* ]] || prefix=${token#*/}
		if [[ $ip =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]]; then
			((BASH_REMATCH[1] <= 255 && BASH_REMATCH[2] <= 255 && BASH_REMATCH[3] <= 255 && BASH_REMATCH[4] <= 255)) || return 1
			[[ -z $prefix ]] || { [[ $prefix =~ ^[0-9]{1,2}$ ]] && ((10#$prefix >= 8 && 10#$prefix <= 32)); } || return 1
		elif [[ $ip =~ ^[0-9A-Fa-f:.]+$ && $ip == *:*:* ]]; then
			[[ -z $prefix ]] || { [[ $prefix =~ ^[0-9]{1,3}$ ]] && ((10#$prefix >= 16 && 10#$prefix <= 128)); } || return 1
		else
			return 1
		fi
	done
}

internal_tls_name() {
	local d=$1
	[[ $d =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] && return 0
	case $d in
	localhost | *.localhost | *.local | *.internal | *.home.arpa) return 0 ;;
	*) return 1 ;;
