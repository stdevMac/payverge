need_value() {
	[[ $# -ge 2 && -n $2 && $2 != -* ]] || die "$1 needs a value (see --help)"
}

while [[ $# -gt 0 ]]; do
	case $1 in
	--domain) need_value "$@" && domain=$2 && shift ;;
	--domain=*) domain=${1#*=} ;;
	--admin-email) need_value "$@" && admin_email=$2 && shift ;;
	--admin-email=*) admin_email=${1#*=} ;;
	--acme-email) need_value "$@" && acme_email=$2 && shift ;;
	--acme-email=*) acme_email=${1#*=} ;;
	--demo) demo=1 ;;
	--no-demo) demo=0 ;;
	--dir) need_value "$@" && install_dir=$2 && shift ;;
	--dir=*) install_dir=${1#*=} ;;
	--version) need_value "$@" && version=$2 && version_requested=1 && shift ;;
	--version=*) version=${1#*=} && version_requested=1 ;;
	--http-port) need_value "$@" && http_port=$2 && shift ;;
	--http-port=*) http_port=${1#*=} ;;
	--https-port) need_value "$@" && https_port=$2 && shift ;;
	--https-port=*) https_port=${1#*=} ;;
	-y | --yes) assume_yes=1 ;;
	--dry-run) dry_run=1 ;;
	--force) force=1 ;;
	--build) build=1 ;;
	--no-backup) no_backup=1 ;;
	--require-signature) require_signature=1 ;;
	--no-start) start=0 ;;
	-h | --help)
		usage
		exit 0
		;;
	*) die "unknown option: $1 (see --help)" ;;
	esac
	shift
done

