version_ge() { # version_ge A B: A >= B (dotted numeric)
	local a b i
	IFS=. read -r -a a <<<"$1"
	IFS=. read -r -a b <<<"$2"
	for i in 0 1 2; do
		((10#${a[i]:-0} > 10#${b[i]:-0})) && return 0
		((10#${a[i]:-0} < 10#${b[i]:-0})) && return 1
	done
	return 0
}

# env_get KEY FILE: last value of KEY in a dotenv file, quotes removed.
env_get() {
	local key=$1 file=$2 line value=""
	[[ -f $file ]] || return 0
	while IFS= read -r line || [[ -n $line ]]; do
		case $line in
		"$key="*) value=${line#*=} ;;
		esac
	done <"$file"
	value=${value%$'\r'}
	if [[ $value == \'*\' || $value == \"*\" ]]; then
		value=${value:1:${#value}-2}
	fi
	printf '%s' "$value"
}

env_has() { # env_has KEY FILE: KEY is set (possibly empty) in FILE
	[[ -f $2 ]] && grep -q "^$1=" "$2"
}

# --- randomness --------------------------------------------------------------

rand_hex() { # rand_hex BYTES
	if have openssl; then
		openssl rand -hex "$1"
	else
		od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'
	fi
}

rand_b64() { # rand_b64 BYTES
	if have openssl; then
		openssl rand -base64 "$1" | tr -d '\n'
	else
		head -c "$1" /dev/urandom | base64 | tr -d '\n'
	fi
}

random_bytes() { # random_bytes N: N decimal byte values, one per line
	if have openssl; then
		openssl rand "$1" | od -An -v -tu1
	else
		od -An -v -N"$1" -tu1 /dev/urandom
	fi | tr -s ' ' '\n' | sed '/^$/d'
}

# 4 groups of 5 from an alphabet without look-alikes (0/O, 1/l/I):
# about 116 bits, easy to type, and it meets the admin password policy.
gen_admin_password() {
	local alphabet="abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
	local n=${#alphabet} limit chars="" byte distinct
	limit=$((256 - 256 % n))
	while :; do
		chars=""
		while [[ ${#chars} -lt 20 ]]; do
			while IFS= read -r byte; do
				((byte < limit)) || continue
				chars+=${alphabet:byte%n:1}
				[[ ${#chars} -lt 20 ]] || break
			done < <(random_bytes 64)
		done
		distinct=$(printf '%s' "$chars" | fold -w1 | sort -u | wc -l | tr -d ' ')
		((distinct >= 8)) && break
	done
	printf '%s-%s-%s-%s' "${chars:0:5}" "${chars:5:5}" "${chars:10:5}" "${chars:15:5}"
}

