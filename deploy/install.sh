#!/usr/bin/env bash
# Payverge installer: one self-hosted instance with Docker Compose.
#
#   curl -fsSL https://github.com/stdevMac/payverge/releases/latest/download/install.sh -o install.sh
#   less install.sh        # read it first
#   bash install.sh
#
# or, from a clone of the repository:
#
#   ./deploy/install.sh    # installs in place, in deploy/
#
# What it does:
#   1. checks Docker Engine and the Compose v2 plugin;
#   2. fetches the deploy files of a release (checksum-verified, and
#      signature-verified when cosign is available) into the install
#      directory, or uses the checkout it runs from;
#   3. asks for the domain, the admin email and demo data (or takes flags);
#   4. writes .env (mode 600) with freshly generated secrets. An existing .env
#      is never overwritten unless you pass --force. A clone never records
#      PAYVERGE_VERSION=latest: a release number, or "local" when building;
#   5. runs `docker compose up -d`, waits for /api/v1/health/ready, probes
#      the public backend and frontend through Caddy, and prints the URL and
#      the generated admin password, once. A failed probe exits non-zero
#      after that summary.
#
# Re-running it is safe: it keeps .env, upgrades the files when you pass
# --version, and starts whatever is not running. Before an upgrade of an
# existing database it takes a backup set (skip with --no-backup). Nothing is
# sent anywhere except the GitHub release download and the image pulls.
#
# Every flag has an environment variable (PAYVERGE_DOMAIN, ...) for
# unattended installs. Run with --help for the list.
set -Eeuo pipefail

readonly REPO="stdevMac/payverge"
# PAYVERGE_RELEASES_URL: a mirror laid out like GitHub releases (download/vX.Y.Z/...).
readonly RELEASES_URL=${PAYVERGE_RELEASES_URL:-https://github.com/${REPO}/releases}
# Keyless identity of the workflow that signs SHA256SUMS (cosign sign-blob --bundle).
readonly RELEASE_SIGNER=https://github.com/stdevMac/payverge/.github/workflows/release.yml@refs/heads/main
readonly MIN_COMPOSE="2.20.0"
readonly READY_TIMEOUT=${PAYVERGE_READY_TIMEOUT:-600}
# Tries, 5 seconds apart, of the public backend and frontend check.
readonly PROBE_ATTEMPTS=${PAYVERGE_PROBE_ATTEMPTS:-24}
# Seconds before a docker call that should answer at once counts as hung.
readonly DOCKER_TIMEOUT=${PAYVERGE_DOCKER_TIMEOUT:-30}
readonly GENERATED_MARK="# ADMIN_PASSWORD was generated by install.sh and is removed after the first start."
# die() exits with this status; the ERR trap stays quiet for it because die
# already said what went wrong.
readonly DIE_STATUS=3

# Files a release (or a checkout) provides. .env, backups/ and rclone/ are the
# operator's and are never touched by an upgrade.
readonly DEPLOY_FILES="docker-compose.yml docker-compose.build.yml Caddyfile Caddyfile.cloudflare payverge.caddy cloudflare-cidrs.caddy .env.example README.md install.sh backup/backup.sh backup/restore.sh postgres/init-app-role.sql monitoring/alerts.yml monitoring/alerts.test.yml"

domain=${PAYVERGE_DOMAIN:-}
admin_email=${PAYVERGE_ADMIN_EMAIL:-}
acme_email=${PAYVERGE_ACME_EMAIL:-}
demo=${PAYVERGE_DEMO:-}
install_dir=${PAYVERGE_DIR:-}
version=${PAYVERGE_INSTALL_VERSION:-}
http_port=${PAYVERGE_HTTP_PORT:-}
https_port=${PAYVERGE_HTTPS_PORT:-}
assume_yes=${PAYVERGE_YES:-0}
dry_run=${PAYVERGE_DRY_RUN:-0}
force=${PAYVERGE_FORCE:-0}
build=${PAYVERGE_BUILD:-0}
no_backup=${PAYVERGE_NO_BACKUP:-0}
require_signature=${PAYVERGE_REQUIRE_SIGNATURE:-0}
start=1
# probe_https records a public check that failed; main warns and exits after
# the summary, so the generated admin password is still printed once.
probe_failed=0
probe_backend_failed=0
probe_frontend_failed=0
probe_scheme=""
probe_bind=""
probe_port=""
version_requested=0
[[ -z $version ]] || version_requested=1

# --- output ------------------------------------------------------------------

if [[ -t 1 ]]; then
	bold=$'\033[1m' dim=$'\033[2m' red=$'\033[31m' yellow=$'\033[33m' green=$'\033[32m' reset=$'\033[0m'
else
	bold="" dim="" red="" yellow="" green="" reset=""
fi

say() { printf '%s\n' "$*"; }
step() { printf '%s==>%s %s\n' "$bold" "$reset" "$*"; }
note() { printf '    %s\n' "$*"; }
warn() { printf '%swarning:%s %s\n' "$yellow" "$reset" "$*" >&2; }
die() {
	printf '%serror:%s %s\n' "$red" "$reset" "$*" >&2
	exit "$DIE_STATUS"
}

# Any other failing command would end the script under `set -e` without a
# word; name it instead. Subshells leave the report to the top level.
on_error() {
	local status=$1 line=$2 command=$3
	((BASH_SUBSHELL == 0)) || return 0
	((status != DIE_STATUS)) || return 0
	[[ $command != '"$@"' ]] || command=$last_run
	# shellcheck disable=SC2016 # the backticks are shown to the operator; they are not expansion
	printf '%serror:%s install.sh stopped at line %s: `%s` failed (exit %s). Nothing after that step ran; fix the cause and run install.sh again.\n' \
		"$red" "$reset" "$line" "$command" "$status" >&2
}
trap 'on_error $? $LINENO "$BASH_COMMAND"' ERR

# run CMD...: execute, or only print it under --dry-run. Never pass a secret
# as an argument to run: it would be printed.
last_run=""
run() {
	if [[ $dry_run == 1 ]]; then
		printf '%s[dry-run]%s %s\n' "$dim" "$reset" "$*"
		return 0
	fi
	last_run="$*"
	"$@"
}

