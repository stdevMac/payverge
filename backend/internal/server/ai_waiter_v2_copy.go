// waiterFinalizerCopy returns the server-owned deterministic copy for a
// canonical guest locale, falling back to English for anything unrecognized.
func waiterFinalizerCopy(locale string) waiterV2Copy {
	if copy, ok := waiterFinalizerCopyByLocale[locale]; ok {
		return copy
	}
	if copy, ok := waiterFinalizerCopyByLocale[normalizeWaiterMenuSnapshotLocale(locale, "")]; ok {
		return copy
	}
	return waiterFinalizerCopyByLocale["en"]
}

// waiterNativeSmallTalkLocale gates the untrusted-prose paths (validated jokes
// and the social reply). Menu answers are fully server-owned in every locale,
// but model prose is only re-checked against en / es forbidden-phrase
// vocabularies, so passing it through in other locales would weaken the
// no-model-facts guarantee.
func waiterNativeSmallTalkLocale(locale string) bool {
	return locale == "en" || locale == "es" || locale == "es-AR"
}
