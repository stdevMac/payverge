package server

import "strings"

// waiterItemPlaceholder is substituted with a sanitized menu entity display
// name. A literal placeholder (rather than a printf verb) keeps operator- or
// model-derived names from ever being read as a format string.
const waiterItemPlaceholder = "{item}"

// waiterListPlaceholder is substituted with a comma-joined allergen list from
// the canonical menu snapshot (issue 816). Same literal-replacement rule as
// waiterItemPlaceholder — never a printf verb.
const waiterListPlaceholder = "{list}"

// Check-math placeholders (issue 943). Every substitution comes from the bill
// row's int64-cent total formatted server-side, so — like the placeholders
// above — they are literal strings and never printf verbs.
const (
	waiterPercentPlaceholder = "{percent}"
	waiterAmountPlaceholder  = "{amount}"
	waiterTotalPlaceholder   = "{total}"
	waiterCountPlaceholder   = "{count}"
)

func waiterCopyWithItem(template, displayName string) string {
	if !strings.Contains(template, waiterItemPlaceholder) {
		return template
	}
	return strings.ReplaceAll(template, waiterItemPlaceholder, displayName)
}

